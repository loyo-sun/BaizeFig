"""Generate paragraph-direction data from Unicode 17 DerivedBidiClass.txt.

Usage: python3 scripts/generate-bidi.py /path/to/DerivedBidiClass.txt
Source: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedBidiClass.txt
Redistribution notice: public/licenses/Unicode.txt
"""
import hashlib
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_bytes()
text = source.decode("utf-8")
if "DerivedBidiClass-17.0.0.txt" not in text:
    raise ValueError("Expected Unicode 17.0.0 data")
classes = bytearray([1]) * 0x110000

def apply(a, b, name):
    start = int(a, 16)
    end = int(b or a, 16)
    value = 1 if name in ("L", "Left_To_Right") else 2 if name in ("R", "AL", "Right_To_Left", "Arabic_Letter") else 3 if name == "B" else 0
    classes[start:end+1] = bytes([value]) * (end-start+1)

for line in text.splitlines():
    match = re.search(r"@missing: ([0-9A-F]+)(?:\.\.([0-9A-F]+))?; (\w+)", line)
    if match:
        apply(*match.groups())
for line in text.splitlines():
    match = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)", line)
    if match:
        apply(*match.groups())
ranges = []
start = 0
for at in range(1, len(classes)+1):
    if at == len(classes) or classes[at] != classes[start]:
        if classes[start]:
            ranges.append(f"  [0x{start:x}, 0x{at-1:x}, {classes[start]}],")
        start = at
header = f'''// Generated by scripts/generate-bidi.py from Unicode 17.0.0.
// Source SHA-256: {hashlib.sha256(source).hexdigest()}
// Copyright Unicode, Inc. See public/licenses/Unicode.txt.
// 1 = L, 2 = R/AL, 3 = paragraph separator; omitted ranges are neutral.
export const bidiRanges: readonly (readonly [number, number, number])[] = [
'''
Path("src/bidiData.ts").write_text(header + "\n".join(ranges) + "\n];\n")
print(f"Generated {len(ranges)} ranges")
