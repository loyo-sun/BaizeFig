import { test, expect } from "@playwright/test";

test("zoom preserves the canvas center and supports custom entry and dismissal", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("baizefig.ui.language", "en"));
  await page.goto("/");
  await expect(page.getByLabel("Saved locally")).toBeVisible();
  const button = page.getByRole("button", { name: "Zoom menu", exact: true });
  const transform = async () => page.locator("svg.design-canvas > g[transform]").first().getAttribute("transform");
  const before = await transform();
  const size = (await page.locator("svg.design-canvas").boundingBox())!;
  await button.click();
  const dialog = page.getByRole("dialog", { name: "Canvas zoom", exact: true });
  const input = dialog.getByRole("spinbutton", { name: "Zoom percentage" });
  await expect(input).toBeFocused();
  await input.fill("125");
  await input.press("Enter");
  await expect(button).toHaveText("125%");
  await expect(dialog).toBeHidden();
  await expect(button).toBeFocused();
  const parse = (value: string) => [...value.matchAll(/-?\d+(?:\.\d+)?/g)].map(match => Number(match[0]));
  const a = parse(before!);
  const b = parse((await transform())!);
  expect((size.width / 2 - a[0]) / a[2]).toBeCloseTo((size.width / 2 - b[0]) / b[2], 5);
  expect((size.height / 2 - a[1]) / a[2]).toBeCloseTo((size.height / 2 - b[1]) / b[2], 5);
  await button.click();
  await input.fill("900");
  await input.press("Enter");
  await expect(dialog).toBeVisible();
  await expect(button).toHaveText("125%");
  await input.press("Escape");
  await expect(dialog).toBeHidden();
  await expect(button).toBeFocused();
  await button.click();
  await page.locator("svg.design-canvas").click({ position: { x: 20, y: 20 } });
  await expect(dialog).toBeHidden();
  await button.click();
  await dialog.getByRole("button", { name: "100%", exact: true }).click();
  await button.click();
  await expect(dialog.getByRole("button", { name: "100%", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.screenshot({ path: "test-results/zoom-experience.png" });
});
